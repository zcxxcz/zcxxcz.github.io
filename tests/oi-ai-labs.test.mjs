test('Held–Karp agrees with exhaustive tours and 2-opt never worsens a route',()=>{
 const points=[[0,0],[1,0],[.8,.8],[.1,1],[.5,.4],[.2,.5]];
 const permute=a=>a.length?a.flatMap((v,i)=>permute(a.filter((_,j)=>i!==j)).map(xs=>[v,...xs])):[[]];
 const brute=Math.min(...permute([1,2,3,4,5]).map(p=>M.tourLength(points,[0,...p]))),opt=M.tspOptimal(points);
 close(opt.length,brute);close(opt.length,M.tourLength(points,opt.route));assert.equal(new Set(opt.route).size,points.length);
 const route=[0,2,1,4,3,5];assert.ok(M.tourLength(points,M.twoOpt(points,route))<=M.tourLength(points,route));
 const options=M.pointerOptions(points,[0,1],.2);close(options.reduce((s,x)=>s+x.p,0),1);assert.ok(options.every(x=>![0,1].includes(x.node)));
});
