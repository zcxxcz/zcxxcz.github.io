const close=(a,b,tol=1e-9)=>assert.ok(Math.abs(a-b)<tol, `${a} ≈ ${b}`);
test('minimax and alpha-beta agree, legal play can hold a draw',()=>{
 const b=[1,0,0,0,-1,0,0,0,1];
 const a=M.tttAnalyze(b,-1,true),plain=M.tttAnalyze(b,-1,false);
 assert.deepEqual(a.scores,plain.scores);assert.ok(a.calls<plain.calls);
 const empty=Array(9).fill(0);assert.equal(M.tttSolve(empty).value,0);
 let player=1;while(M.tttMoves(empty).length){empty[M.tttSolve(empty,player).move]=player;player=-player;}
 assert.equal(M.tttWinner(empty),0);
});
test('Viterbi matches exhaustive path enumeration',()=>{
 const obs=[1,0,1,1,0,1];for(const stay of [.1,.5,.9]){
 const result=M.hmmViterbi(obs,stay);let best=0;
 for(let mask=0;mask<1<<obs.length;mask++)best=Math.max(best,M.hmmPathProbability(obs.map((_,i)=>mask>>i&1),obs,stay));
 close(Math.exp(result.logProbability),best);close(M.hmmPathProbability(result.path,obs,stay),best);
 }
});
test('BPE is lossless and handles overlapping pair counts',()=>{
 let tokens=[...'aaaa low lower low'];const text=tokens.join('');
 const repeated=M.bpeStep([...'aaaa']);assert.equal(repeated.count,3);assert.equal(repeated.merged,2);
 for(let n=0;n<30;n++){const next=M.bpeStep(tokens);if(!next)break;assert.ok(next.tokens.length<tokens.length);tokens=next.tokens;assert.equal(tokens.join(''),text);}
});
test('Bellman reference satisfies recurrence, sampled Q training learns a useful policy',()=>{
 const opt=M.gridOptimal(0);for(let s=0;s<16;s++)if(!M.gridTerminal(s))close(opt.values[s],Math.max(...opt.q[s]));
 const q=M.createQLearner(7,0);const before=M.evaluateQ(q);M.trainQ(q,1000);const after=M.evaluateQ(q);
 assert.equal(before.success,0);assert.equal(after.success,1);assert.ok(after.return>before.return);
 for(const slip of [0,.1,.3])for(let s=0;s<16;s++)for(let a=0;a<4;a++)close(M.gridTransitions(s,a,slip).reduce((sum,t)=>sum+t.p,0),1);
});
