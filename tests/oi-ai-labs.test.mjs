test('reverse DAG accumulates shared-parent gradient and matches finite differences',()=>{
 const params={x:1.2,w:.6,b:-.2,y:1},result=M.autodiff(params);
 for(const [i,key] of ['x','w','b','y'].entries()){
 const eps=1e-5,a=M.autodiff({...params,[key]:params[key]+eps}).loss,b=M.autodiff({...params,[key]:params[key]-eps}).loss;
 close(result.gradients[i],(a-b)/(2*eps),1e-8);
 }
 close(result.gradients[6],2*(params.x*params.w+params.b-params.y));
});
